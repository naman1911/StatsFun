// Converts docs/curriculum.md into js/data/curriculum.js.
// Usage: node tools/convert.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../docs/curriculum.md', import.meta.url), 'utf8');
const lines = src.split('\n');

const FIELD_KEYS = {
  'Name': 'name', 'Synonyms/notation': 'synonyms', 'Definition': 'definition', 'Formula/procedure': 'formula',
  'Prerequisites': 'prereqs', 'Misconception': 'misconception', 'Real-world example': 'example', 'Difficulty tier': 'tier',
  'Game name': 'gameName', 'Goal': 'goal', 'Interaction': 'interaction', 'Data generation': 'dataGen', 'Scoring': 'scoring',
  'Reveal': 'reveal', 'Why it works': 'why', 'Engine type': 'engine',
  'Scenario': 'scenario', 'Concepts combined': 'concepts', 'Mechanic': 'mechanic', 'Win condition': 'win',
};

const worlds = [], bosses = [], badges = [];
let world = null, concept = null, boss = null, section = '';

for (const raw of lines) {
  const line = raw.trimEnd();
  let m;
  if ((m = line.match(/^## World (\d+) — (.+?) \((.+)\)$/))) {
    world = { num: +m[1], id: `w${m[1]}`, name: m[2], tier: m[3], theme: '', concepts: [] };
    worlds.push(world); section = 'world'; concept = null; continue;
  }
  if (line.startsWith('## ')) { section = line.slice(3).trim(); concept = null; boss = null; continue; }
  if (section === 'world' && world && (m = line.match(/^Theme: (.+)$/))) { world.theme = m[1]; continue; }
  if (section === 'world' && (m = line.match(/^### (W\d+\.\d+) (.+)$/))) {
    concept = { id: m[1], title: m[2], world: world.id };
    world.concepts.push(concept); continue;
  }
  if (section === 'Boss levels' && (m = line.match(/^### (B\d+) (.+?) \((.+?)\) — (.+)$/))) {
    boss = { id: m[1], title: m[2], placement: m[3], tier: m[4] };
    bosses.push(boss); continue;
  }
  if ((m = line.match(/^- \*\*(.+?):\*\* ?(.*)$/))) {
    const key = FIELD_KEYS[m[1]];
    const target = section === 'Boss levels' ? boss : concept;
    if (key && target) target[key] = m[2].trim();
    continue;
  }
  if (section === 'Badges and achievements' && (m = line.match(/^\| (.+?) \| (.+?) \|$/)) && m[1] !== 'Badge' && !m[1].startsWith('-')) {
    badges.push({ name: m[1], condition: m[2] });
  }
}

// Normalise a few fields.
const parseIds = (s) => (s.match(/[WB]\d+\.?\d*/g) || []);
for (const w of worlds) for (const c of w.concepts) {
  c.prereqs = c.prereqs === '—' ? [] : parseIds(c.prereqs || '');
  c.engine = (c.engine || 'QUIZ').replace(/^NEW: /, '').replace(/\s*\(.*$/, '').trim();
}
for (const b of bosses) {
  // Expand ranges like W1.02–W1.06 into individual ids.
  const ids = [];
  for (const part of (b.concepts || '').split(/,\s*/)) {
    const r = part.match(/(W\d+)\.(\d+)[–-](W\d+)\.(\d+)/);
    if (r) { for (let k = +r[2]; k <= +r[4]; k++) ids.push(`${r[1]}.${String(k).padStart(2, '0')}`); }
    else ids.push(...parseIds(part));
  }
  b.concepts = ids;
  b.afterWorld = /final boss/.test(b.placement) ? worlds.length : Math.max(...(b.placement.match(/World (\d+)(?:–(\d+))?/) || []).slice(1).filter(Boolean).map(Number));
}

const total = worlds.reduce((n, w) => n + w.concepts.length, 0);
const out = `// GENERATED by tools/convert.mjs from docs/curriculum.md. Do not edit by hand.
export const WORLDS = ${JSON.stringify(worlds, null, 1)};
export const BOSSES = ${JSON.stringify(bosses, null, 1)};
export const BADGES = ${JSON.stringify(badges, null, 1)};
export const CONCEPTS = Object.fromEntries(WORLDS.flatMap((w) => w.concepts.map((c) => [c.id, c])));
`;
writeFileSync(new URL('../js/data/curriculum.js', import.meta.url), out);
console.log(`worlds=${worlds.length} concepts=${total} bosses=${bosses.length} badges=${badges.length}`);
